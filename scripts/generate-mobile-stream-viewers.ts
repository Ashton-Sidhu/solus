import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'

// The device and browser viewers run inside a WebView, so each is one script the app embeds as text.
const viewers = [
  { entry: 'apps/mobile/src/features/devices/device-stream.browser.ts', output: 'apps/mobile/src/features/devices/device-stream-source.generated.ts', name: 'deviceStreamSource', globalName: 'SolusDeviceStream' },
  { entry: 'apps/mobile/src/features/browser/preview-stream.browser.ts', output: 'apps/mobile/src/features/browser/preview-stream-source.generated.ts', name: 'previewStreamSource', globalName: 'SolusPreviewStream' },
]
for (const viewer of viewers) {
  const result = await build({ entryPoints: [viewer.entry], bundle: true, write: false, minify: true, format: 'iife', globalName: viewer.globalName, target: 'es2022' })
  await writeFile(viewer.output, `// Generated by bun scripts/generate-mobile-stream-viewers.ts. Do not edit.\nexport const ${viewer.name} = ${JSON.stringify(result.outputFiles[0]!.text)}\n`)
}
