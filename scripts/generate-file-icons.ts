import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import sharp from "sharp";
import { FILE_ICON_TOKENS, fileIconSvg } from "../packages/client-core/src/file-icons";

// Native Markdown needs PNGs. Generate them from the same SVGs as desktop/web.
const mobile = resolve(import.meta.dir, "../apps/mobile");
await mkdir(`${mobile}/assets/file-icons`, { recursive: true });
for (const token of FILE_ICON_TOKENS) {
  const svg = fileIconSvg(token).replace("<svg", '<svg xmlns="http://www.w3.org/2000/svg"');
  // Covers a 32-point icon on a 3x phone display.
  await sharp(Buffer.from(svg)).resize(96, 96).png().toFile(`${mobile}/assets/file-icons/pierre_${token}.png`);
}
await writeFile(`${mobile}/src/lib/markdownFileIcons.generated.ts`, `// Generated by scripts/generate-file-icons.ts. Do not edit by hand.
import type { ImageSourcePropType } from "react-native";
import type { FileIconToken } from "@solus/client-core/file-icons";

export const MARKDOWN_FILE_ICON_SOURCES = {
${FILE_ICON_TOKENS.map((token) => `  ${token}: require("../../assets/file-icons/pierre_${token}.png"),`).join("\n")}
} as const satisfies Readonly<Record<FileIconToken, ImageSourcePropType>>;
`);
